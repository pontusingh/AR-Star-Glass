def fmt_float(v, digits=5):
    """格式化浮点数并补 f 后缀（C 字面量）。"""
    return f"{v:.{digits}f}f"


def main():
    lines = []
    lines.append("// 本文件由 tools/gen_star_catalog.py 自动生成 —— 请勿手工编辑。")
    lines.append("// 数据来源：ESA Hipparcos 星表（J2000 历元，坐标截断至 0.001 度），")
    lines.append("// 取全天视星等最亮的 60 颗恒星（均含通行中文名）。")
    lines.append("// 重新生成：python tools/gen_star_catalog.py")
    lines.append('#include "StarCatalog.h"')
    lines.append("")
    lines.append("// 星表本体：const 数组直接落在 flash 映射区（.rodata），不占用 RAM。")
    lines.append("const CatalogStar STAR_CATALOG[] = {")
    lines.append("    // {HIP编号, 赤经J2000(小时), 赤纬J2000(度), 视星等, ASCII名, 中文名}")
    for hip, ra_deg, dec_deg, mag, ascii_name, cn_name in STARS:
        ra_hours = ra_deg / 15.0  # 引擎恒星路径接口使用赤经小时单位
        lines.append(
            "    {{{hip}, {ra}, {dec}, {mag}, \"{a}\", \"{cn}\"}},".format(
                hip=hip,
                ra=fmt_float(ra_hours),
                dec=fmt_float(dec_deg),
                mag=fmt_float(mag, 2),
                a=ascii_name,
                cn=cn_name,
            )
        )
    lines.append("};")
    lines.append("")
    lines.append("const int STAR_CATALOG_COUNT = sizeof(STAR_CATALOG) / sizeof(STAR_CATALOG[0]);")
    lines.append("")

    out_path = os.path.join(os.path.dirname(__file__), "..", "src", "data", "StarCatalogData.cpp")
    out_path = os.path.normpath(out_path)
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"已生成 {out_path}（{len(STARS)} 颗恒星）")


if __name__ == "__main__":
    main()
